#!/usr/bin/env python3
"""Regenerate webapp/src/utils/agendaEngineData.js: the firmware's bitmap font and weather icons as hex.

The colour profile editor (webapp/public/profile-editor.html) draws its preview with a JavaScript port of the
firmware's Agenda renderer (webapp/src/utils/agendaEngine.js). The port needs the same bitmaps the firmware
draws with: the 17x24 text font (components/epaper_src/Fonts/font24.c) and the 24x24 weather icons of both
icon sets (main/weather_icons_data.h). This script reads those two C files and writes them as hex strings.

    python scripts/gen_agenda_engine_data.py
    (cd webapp && npx prettier --write src/utils/agendaEngineData.js)

Run it again when either C file changes (scripts/sync_profile_editor.py then copies the data into the editor page).
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONT_C = os.path.join(ROOT, "components", "epaper_src", "Fonts", "font24.c")
ICONS_H = os.path.join(ROOT, "main", "weather_icons_data.h")
OUT = os.path.join(ROOT, "webapp", "src", "utils", "agendaEngineData.js")

GLYPHS = 95  # ' ' .. '~'
GLYPH_BYTES = 24 * 3
ICON_COUNT = 17
ICON_BYTES = 24 * 3


def hex_bytes(text):
    return [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", text)]


def read_font():
    src = open(FONT_C, encoding="utf-8").read()
    body = src[src.index("Font24_Table[]") :]
    body = body[body.index("{") : body.index("};")]
    data = hex_bytes(body)
    if len(data) != GLYPHS * GLYPH_BYTES:
        sys.exit("font24.c: %d bytes, expected %d" % (len(data), GLYPHS * GLYPH_BYTES))
    return data


def read_icons():
    src = open(ICONS_H, encoding="utf-8").read()
    arrays = {}
    for name, body in re.findall(
        r"static const uint8_t (weather_icon_\w+)\[\] = \{(.*?)\};", src, re.S
    ):
        arrays[name] = hex_bytes(body)
    sets = {}
    for icon_set in ("flaticon", "metno"):
        table = re.search(
            r"weather_icon_table_%s\[WEATHER_ICON_COUNT\] = \{(.*?)\};" % icon_set,
            src,
            re.S,
        ).group(1)
        names = re.findall(r"(weather_icon_\w+),", table)
        if len(names) != ICON_COUNT:
            sys.exit("%s: %d icons, expected %d" % (icon_set, len(names), ICON_COUNT))
        sets[icon_set] = [arrays[n] for n in names]
        for data in sets[icon_set]:
            if len(data) != ICON_BYTES:
                sys.exit("%s: an icon has %d bytes" % (icon_set, len(data)))
    return sets


def as_hex(data):
    return "".join("%02x" % b for b in data)


def main():
    font = read_font()
    icons = read_icons()
    lines = [
        "// Generated by scripts/gen_agenda_engine_data.py - do not edit by hand.",
        "// The firmware's 17x24 text font (95 glyphs, ' ' to '~', 24 rows of 3 bytes, MSB first) and its",
        "// 24x24 weather icons (17 per icon set), as hex strings.",
        "",
        'export const FONT24_HEX = "%s";' % as_hex(font),
        "",
        "export const ICON_HEX = {",
    ]
    for icon_set, items in icons.items():
        lines.append("  %s: [" % icon_set)
        for data in items:
            lines.append('    "%s",' % as_hex(data))
        lines.append("  ],")
    lines.append("};")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("written %s (%d bytes)" % (OUT, os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
